def _dockerfile() -> str:
    return """FROM node:22-alpine
WORKDIR /app
COPY package*.json ./
RUN npm install --omit=dev
COPY src ./src
EXPOSE 3000
CMD [\"npm\", \"start\"]
"""


TEMPLATES = {
    "src/app.js": _app_js,
    "src/routes/game.js": _game_router_js,
    "src/services/questionService.js": _question_service_js,
    "src/data/questions.js": _questions_js,
    "tests/app.test.js": _test_js,
    "Dockerfile": _dockerfile,
}


def _safe_destination(project_directory: Path, relative_path: str) -> Path:
    destination = (project_directory / relative_path).resolve()
    try:
        destination.relative_to(project_directory.resolve())
    except ValueError as error:
        raise GenerationError(f"Refusing to write outside project: {relative_path}") from error
    return destination


def _write_text(project_directory: Path, relative_path: str, content: str) -> None:
    destination = _safe_destination(project_directory, relative_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(content, encoding="utf-8")


def generate_project(
    specification: ArchitectureSpec, plan: GenerationPlan, output_directory: Path
) -> Path:
    """Generate every planned artifact and return the project directory."""
    project_directory = (output_directory / plan.target_directory).resolve()
    try:
        project_directory.relative_to(output_directory.resolve())
    except ValueError as error:
        raise GenerationError("The plan target must stay inside output/.") from error

    project_directory.mkdir(parents=True, exist_ok=True)
    _write_text(project_directory, "package.json", _package_json(specification))
    _write_text(project_directory, "README.md", _readme(specification))
    _write_text(project_directory, ".dockerignore", "node_modules\nnpm-debug.log\n.git\n")
    specification.write_json(_safe_destination(project_directory, "architecture_spec.json"))

    for relative_path, template in TEMPLATES.items():
        _write_text(project_directory, relative_path, template())

    generated_paths = {
        path.relative_to(project_directory).as_posix()
        for path in project_directory.rglob("*")
        if path.is_file()
    }
    planned_paths = {planned_file.path for planned_file in plan.files}
    missing_paths = planned_paths - generated_paths
    if missing_paths:
        raise GenerationError(f"Generator missed planned files: {sorted(missing_paths)}")
    return project_directory
