"""Generate a small, runnable Express project from a validated plan."""

from __future__ import annotations

import json
from pathlib import Path

from agent.planner import GenerationPlan
from agent.specification import ArchitectureSpec


class GenerationError(ValueError):
    """Raised when generation would write outside the approved target directory."""


def _package_json(specification: ArchitectureSpec) -> str:
    package = {
        "name": specification.project_name,
        "version": "1.0.0",
        "private": True,
        "description": "Generated starter for the Space Fractions learning game.",
        "main": "src/app.js",
        "scripts": {"start": "node src/app.js", "test": "node --test"},
        "dependencies": {"express": "^4.21.2"},
    }
    return json.dumps(package, ensure_ascii=False, indent=2) + "\n"


def _app_js() -> str:
    return """const express = require(\"express\");
const { createGameRouter } = require(\"./routes/game\");

const app = express();
app.use(express.json());

app.get(\"/health\", (request, response) => {
  response.status(200).json({ status: \"ok\" });
});

app.use(createGameRouter());

app.use((request, response) => {
  response.status(404).json({ error: \"Route not found\" });
});

if (require.main === module) {
  const port = process.env.PORT || 3000;
  app.listen(port, () => {
    console.log(`Space Fractions API listening on port ${port}`);
  });
}

module.exports = app;
"""


def _game_router_js() -> str:
    return """const express = require(\"express\");
const {
  getQuestionForGame,
  evaluateAnswer,
} = require(\"../services/questionService\");

function createGameRouter() {
  const router = express.Router();

  router.get(\"/play\", (request, response) => {
    const gameId = 1;
    response.status(200).json({
      gameId,
      status: \"started\",
      question: getQuestionForGame(gameId),
    });
  });

  router.post(\"/play/:gameId/answer\", (request, response) => {
    const gameId = Number(request.params.gameId);
    const result = evaluateAnswer(gameId, request.body.answer);
    response.status(200).json({ gameId, ...result });
  });

  router.get(\"/scores/:gameId\", (request, response) => {
    response.status(200).json({
      gameId: Number(request.params.gameId),
      score: 0,
    });
  });

  return router;
}

module.exports = { createGameRouter };
"""


def _question_service_js() -> str:
    return """const { questions } = require(\"../data/questions\");

function getQuestionForGame(gameId) {
  const question = questions[(gameId - 1) % questions.length];
  return {
    id: question.id,
    prompt: question.prompt,
    options: question.options,
  };
}

function evaluateAnswer(gameId, answer) {
  const question = questions[(gameId - 1) % questions.length];
  return {
    correct: answer === question.answer,
    correctAnswer: question.answer,
  };
}

module.exports = { getQuestionForGame, evaluateAnswer };
"""


def _questions_js() -> str:
    return """const questions = [
  {
    id: \"fraction-1\",
    prompt: \"Which fraction is equal to one half?\",
    options: [\"1/2\", \"1/3\", \"2/3\", \"3/4\"],
    answer: \"1/2\",
  },
];

module.exports = { questions };
"""


def _test_js() -> str:
    return """const assert = require(\"node:assert/strict\");
const test = require(\"node:test\");
const app = require(\"../src/app\");

async function requestApplication(path) {
  const server = app.listen(0, \"127.0.0.1\");
  await new Promise((resolve) => server.once(\"listening\", resolve));

  try {
    const { port } = server.address();
    return await fetch(`http://127.0.0.1:${port}${path}`);
  } finally {
    await new Promise((resolve, reject) => {
      server.close((error) => (error ? reject(error) : resolve()));
    });
  }
}

test(\"GET /health reports a healthy service\", async () => {
  const response = await requestApplication(\"/health\");
  assert.equal(response.status, 200);
  assert.deepEqual(await response.json(), { status: \"ok\" });
});

test(\"GET /play starts a game and returns a fraction question\", async () => {
  const response = await requestApplication(\"/play\");
  const body = await response.json();
  assert.equal(response.status, 200);
  assert.equal(body.gameId, 1);
  assert.ok(body.question.prompt);
});
"""


